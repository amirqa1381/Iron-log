// Helper to query exercises with rich filtering
export function queryExercises({ category, equipment, location, difficulty, query, limit = 50, offset = 0 } = {}) {
  let list = EXERCISES_LIBRARY;

  if (category && category !== 'all') {
    list = list.filter(e => e.category === category);
  }
  if (equipment && equipment !== 'all') {
    list = list.filter(e => e.equipment === equipment);
  }
  if (location && location !== 'all') {
    list = list.filter(e => e.location === location || e.location === 'all');
  }
  if (difficulty && difficulty !== 'all') {
    list = list.filter(e => e.difficulty === difficulty);
  }
  if (query) {
    const q = query.toLowerCase().trim();
    list = list.filter(e => 
      e.name.toLowerCase().includes(q) || 
      e.nameFa.includes(q) ||
      (e.target && e.target.includes(q))
    );
  }

  const total = list.length;
  const paginated = list.slice(offset, offset + limit);

  return { total, exercises: paginated };
}

export function getExerciseById(id) {
  const numId = Number(id);
  return EXERCISES_LIBRARY.find(e => e.id === numId) || null;
}
